"""v0.2.55 — Verify WebAuthn Android signed-app origins without weakening RP ID.

All credentials are generated by a local software authenticator. This never
uses an Android biometric, private signing key, production owner token,
Public API, Render network, or any live market/trading activity.
"""
import base64
import hashlib
import importlib
import os
import tempfile
import unittest
from unittest.mock import patch

from engine import identity_auth, tenant_foundation, tenant_passkeys
from test_two_user_real_crypto_webauthn_v0241 import LocalAuthenticator

RP = "staging-edgepilot.belenoscreations.biz"
ORIGIN = "https://" + RP
CERT = "B1:D5:C5:60:11:10:D4:B3:BF:5A:22:D4:4A:F5:6E:A7:BA:8C:24:F0:46:FA:DB:27:95:2A:EA:18:E7:EC:D3:3F"
NATIVE = ("android:apk-key-hash:" +
          base64.urlsafe_b64encode(bytes.fromhex(CERT.replace(":", "")))
          .rstrip(b"=").decode("ascii"))
PASSWORD = "Safe-Synthetic-Test-Passkey-Password-2026"


class StagingAuthenticator(LocalAuthenticator):
    @staticmethod
    def _rp_hash():
        return hashlib.sha256(RP.encode("utf-8")).digest()


class NativeAndroidPasskeyOriginTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory(prefix="edge-native-passkey-", dir="/tmp")
        self.env = patch.dict(os.environ, {
            "EDGE_DB_PATH": self.tmp.name + "/native-passkey.db",
            "EDGE_ISOLATED_STAGING": "true",
            "EDGE_ANDROID_CERT_SHA256": CERT,
            "EDGE_ANDROID_ASSOCIATION_PACKAGE": "com.edgepilot.mobile.staging",
            "EDGE_WEBAUTHN_RP_ID": RP,
            "EDGE_WEBAUTHN_ORIGIN": ORIGIN,
            "EDGE_APP_TOKEN": "",
            "PUBLIC_API_SECRET": "",
            "EDGE_CREDENTIAL_KEY": "",
            "EDGE_TENANT_SCHEMA_PREPARE": "true",
            "EDGE_IDENTITY_AUTH_ENABLED": "true",
            "EDGE_TENANT_SIGNUP_ENABLED": "true",
            "EDGE_TENANT_PASSKEYS_ENABLED": "true",
            "EDGE_TENANT_PASSWORD_CHANGE_ENABLED": "false",
            "EDGE_TENANT_SESSION_CONTROLS_ENABLED": "false",
            "EDGE_AUTOMATION_WORKER_ENABLED": "false",
            "ENABLE_LIVE_ORDERS": "false",
            "EDGE_TENANT_PUBLIC_VAULT_ENABLED": "false",
            "EDGE_TENANT_PUBLIC_READONLY_ENABLED": "false",
            "EDGE_TENANT_ACCOUNT_READS_ENABLED": "false",
            "EDGE_TENANT_MONITOR_PREVIEW_ENABLED": "false",
            "EDGE_TENANT_WATCHLIST_EDIT_ENABLED": "false",
        })
        self.env.start()
        import app
        self.module = importlib.reload(app)
        self.client = self.module.app.test_client()
        self.user_id = tenant_foundation.TenantStore(str(self.module.DB)).provision_user(
            "Signed Android test identity")
        self.module.identity_store.provision(
            self.user_id, "native_staging_test", PASSWORD)
        result = self.post(self.client, "/api/identity/login", {
            "username": "native_staging_test", "password": PASSWORD})
        self.assertEqual(result.status_code, 200, result.get_data(as_text=True))
        self.csrf = result.get_json()["csrf"]

    def tearDown(self):
        self.env.stop()
        import app
        importlib.reload(app)
        self.tmp.cleanup()

    def post(self, client, path, payload, csrf=None):
        headers = {"Origin": ORIGIN}
        if csrf is not None:
            headers["X-Edge-Identity-CSRF"] = csrf
        return client.post(path, base_url=ORIGIN, headers=headers, json=payload)

    def begin(self):
        r = self.post(self.client, "/api/identity/passkeys/register/options",
                      {}, self.csrf)
        self.assertEqual(r.status_code, 200, r.get_data(as_text=True))
        return r.get_json()

    def register(self, auth, origin):
        data = self.begin()
        return self.post(self.client, "/api/identity/passkeys/register/finish", {
            "requestId": data["requestId"],
            "credential": auth.registration(data["publicKey"], origin=origin),
        }, self.csrf)

    def test_android_native_origin_with_actual_pinned_public_cert_roundtrip(self):
        store = self.module.tenant_passkey_store
        self.assertEqual(store.allowed_origins, [ORIGIN, NATIVE])
        auth = StagingAuthenticator()
        result = self.register(auth, NATIVE)
        self.assertEqual(result.status_code, 200, result.get_data(as_text=True))
        self.assertTrue(result.get_json()["registered"])
        self.assertFalse(result.get_json()["tradingEnabled"])
        fresh = self.module.app.test_client()
        started = self.post(fresh, "/api/identity/passkeys/authenticate/options",
                            {})
        self.assertEqual(started.status_code, 200, started.get_data(as_text=True))
        data = started.get_json()
        response = self.post(fresh, "/api/identity/passkeys/authenticate/finish", {
            "requestId": data["requestId"],
            "credential": auth.assertion(data["publicKey"], self.user_id,
                                         origin=NATIVE),
        })
        self.assertEqual(response.status_code, 200, response.get_data(as_text=True))
        self.assertIsInstance(response.get_json()["csrf"], str)

    def test_https_web_login_origin_is_still_accepted(self):
        auth = StagingAuthenticator()
        result = self.register(auth, ORIGIN)
        self.assertEqual(result.status_code, 200, result.get_data(as_text=True))
        self.assertFalse(result.get_json()["brokerAccessAuthorized"])

    def test_wrong_native_origin_and_unowned_browser_origin_rejected(self):
        for origin in (
            "android:apk-key-hash:" + "A" * 43,
            "android:apk-key-hash:" + "a" * 43,
            "https://edgepilot.belenoscreations.biz",
            "https://attacker.example",
            "http://" + RP,
            NATIVE + "extra",
        ):
            with self.subTest(origin=origin):
                auth = StagingAuthenticator()
                response = self.register(auth, origin)
                self.assertEqual(response.status_code, 400)
                self.assertEqual(response.get_json()["error"],
                                 "Passkey verification failed")
        self.assertEqual(self.module.tenant_passkey_store.redacted_own_status(
            self.client.get_cookie(identity_auth.COOKIE_NAME, domain=RP).value,
            self.csrf)["activePasskeys"], 0)

    def test_cryptographic_and_challenge_verification_not_bypassed(self):
        auth = StagingAuthenticator()
        begun = self.begin()
        bad = auth.registration(begun["publicKey"], origin=NATIVE)
        bad["response"]["clientDataJSON"] = base64.urlsafe_b64encode(
            b'{"type":"webauthn.create","challenge":"tampered","origin":"' +
            NATIVE.encode("ascii") + b'","crossOrigin":false}'
        ).rstrip(b"=").decode("ascii")
        response = self.post(self.client, "/api/identity/passkeys/register/finish", {
            "requestId": begun["requestId"], "credential": bad,
        }, self.csrf)
        self.assertEqual(response.status_code, 400)
        self.assertEqual(self.register(StagingAuthenticator(), NATIVE).status_code, 200)

    def test_default_store_remains_https_only_even_with_android_cert_in_env(self):
        https_only = tenant_passkeys.TenantPasskeyStore(
            str(self.module.DB), self.module.identity_store,
            rp_id=RP, expected_origin=ORIGIN)
        self.assertEqual(https_only.allowed_origins, ORIGIN)
        auth = StagingAuthenticator()
        begun = https_only.begin_registration(
            self.client.get_cookie(identity_auth.COOKIE_NAME, domain=RP).value,
            self.csrf)
        with self.assertRaises(tenant_passkeys.PasskeyDenied):
            https_only.finish_registration(
                self.client.get_cookie(identity_auth.COOKIE_NAME, domain=RP).value,
                self.csrf, begun["requestId"],
                auth.registration(begun["publicKey"], origin=NATIVE))

    def test_public_certificate_digest_is_strictly_validated(self):
        self.assertEqual(
            tenant_passkeys._android_native_origin_from_pinned_cert(CERT), NATIVE)
        for bad in ("", "AA" * 32, "ZZ:" * 31 + "00",
                    "AA:" * 31 + "A", " " + CERT, CERT + " "):
            with self.subTest(bad=bad):
                with self.assertRaises(ValueError):
                    tenant_passkeys._android_native_origin_from_pinned_cert(bad)


if __name__ == "__main__":
    unittest.main()
